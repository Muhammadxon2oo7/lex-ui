// QA: the drafting room — the claim fills in on the sheet lying on the 3D desk. Usage: node tools/qa/draft.mjs [outDir]
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const OUT = process.argv[2] ?? 'qa-shots';
const BASE = process.env.BASE ?? 'http://localhost:3000';
mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch({ args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 810 } });
const logs = [];
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message.slice(0, 300)}`));
page.on('console', (m) => m.type() === 'error' && logs.push(`[error] ${m.text().slice(0, 200)}`));
await page.goto(`${BASE}/`);
await page.evaluate(() => localStorage.setItem('lexsim.profile.v1', JSON.stringify({ name: 'Karimova Aziza', avatar: 'woman', role: 'student' })));
const id = await page.evaluate(async () => (await (await fetch('/api/v1/cases', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{"fresh":true}' })).json()).case.caseId);
await page.goto(`${BASE}/ish/${id}/draft`);
await page.getByRole('dialog', { name: /Daʼvo arizasini tuzish/ }).waitFor({ timeout: 30000 });
await page.waitForTimeout(5000);
await page.screenshot({ path: `${OUT}/d1-blank.png` });
await page.getByRole('radio', { name: /Fuqarolik ishlari boʻyicha Namuna tumanlararo/ }).click();
await page.getByRole('checkbox', { name: /Vakil maʼlumotlarini/ }).check();
await page.getByRole('radio', { name: /Namuna Savdo» MChJ \(ish beruvchi/ }).click();
await page.getByRole('radio', { name: /Ishga tiklash va majburiy/ }).click();
for (const t of ['Javobgar: «Namuna', 'Boʻshatish buyrugʻi 14', 'kasal boʻlgan', 'telefonda xabar']) await page.getByRole('button', { name: new RegExp(t) }).click();
await page.getByRole('checkbox', { name: /Pochta xarajatlari/ }).check();
const box = await page.getByLabel(/Imzo maydoni/).boundingBox();
await page.mouse.move(box.x + 30, box.y + 60); await page.mouse.down();
for (let i = 0; i < 18; i++) await page.mouse.move(box.x + 30 + i * 12, box.y + 50 + Math.sin(i) * 18);
await page.mouse.up();
await page.waitForTimeout(1500);
await page.screenshot({ path: `${OUT}/d2-filled.png` });
await page.getByRole('button', { name: /Qogʻozni yaqindan/ }).click();
await page.waitForTimeout(700);
await page.screenshot({ path: `${OUT}/d3-zoom.png` });
console.log(logs.join('\n') || 'no console errors');
await browser.close();
